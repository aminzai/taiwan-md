/**
 * tw-variant-chars.mjs — 台灣標準採用的「簡體長相」字元白名單（單一 SSOT）
 *
 * 為什麼需要這份清單：判「這段中文有沒有混進簡體」不能只問 OpenCC 有沒有轉換。
 * 程式化的 candidate 判定是「s2t(C) !== C 且 t2s(C) === C ⇒ C 是某組簡繁對的簡體側」,
 * 但台灣標準**本來就採用**一批長得像簡體的字（占／岩／斗／杰⋯），OpenCC 會硬把它們
 * 「更正」成 佔／巖／鬥／傑，造成大量誤報。
 *
 * 誤報的代價不是噪音而是損害：閘門會誘導作者把正確的台灣用語改掉換綠燈
 * （2026-08-09 LESSONS `gate-triggers-content-degradation-incentive`）。最壞的一種是
 * 改人名——「楊双子」是台灣作家自己的筆名寫法，「藍挹丰」是真人姓名，OpenCC 想把
 * 它們改成「楊雙子」「藍挹豐」。一個做主權保存的站，閘門不該改台灣人的名字。
 *
 * ── 校準紀錄 ──────────────────────────────────────────────────────────
 *
 * **v1（2026-07-10，terminology-charcheck.js）**：白名單從 `data/terminology/*.yaml`
 * 的 display.taiwan 欄實際出現的 candidate 反推（該語料 2,394 條詞目，dual-status 字
 * 12 種、真外洩只有「乌」1 種）。
 *
 * **v2（2026-08-17，本檔誕生）**：語料換成 `knowledge/` 939 篇中文文章重跑同一支
 * candidate 判定，白名單外還有 173 種字元命中、前 20 名全部是誤報：
 *
 *   占 522（占比／占 GDP，主計總處官方表格就寫「占」——本次 /budget 頁面
 *          12 筆誤報全來自這個字，是 v2 的觸發事件）
 *   岩 422（岩層／岩石，「巖」是罕用異體）· 斗 228（北斗／斗六／漏斗）
 *   杰 186（人名）· 征 170（征服／遠征）· 准 166（准許／批准）
 *   干 159（干擾／天干）· 庄 135（台灣地名與姓名：新庄／庄國榮）
 *   余 94（姓氏）· 双 73（作家楊双子）· 朴 67（朴子／朴姓）
 *   虱 66（虱目魚——台灣標準寫法）· 咸 63（咸豐）· 灶 35（灶神／灶腳）
 *   愿 32・丰 31（多為引用外語來源原標題與真人姓名）· 丑 20（丑角／生肖）
 *   划 19（划船）
 *
 * ⚠️ **但「湾／国／愿」刻意不進白名單**，即使語料裡它們也全出現在合法引用中
 * （日文書名《帝國主義下の台湾》、RFI 標題「鼎泰丰宣布关闭中国华北」、
 * 「日本国立国会図書館」）。理由是**校準語料不等於使用者的掃描範圍**：那些引用
 * 住在 `knowledge/` 的腳註裡，而使用這份白名單的兩支檢查器掃的是 `src/i18n/*.ts`
 * 與 `data/terminology/*.yaml`——在**那裡**寫出「台湾」「中国」幾乎不可能是引用，
 * 就是譯文掉回中文或簡體外洩，而且正是這兩支檢查器存在的理由（2026-08-11 的
 * ar 區塊整段「台湾前 50 大企业」就是這個形狀）。拿 A 語料的誤報率去放寬 B 語料的
 * 判準，是量錯層（REFLEXES #16 量測層延伸）。`knowledge/` 腳註引用那一層有自己的
 * 檢查器（cjk-leak-check 家族），該在那裡處理。
 *
 * ── 分區設計（v2 關鍵）───────────────────────────────────────────────
 *
 * `TW_ACCEPTED_VARIANTS` 只給**中文區塊**（zh-TW）用——那裡的作者正在合法書寫台灣
 * 中文、引用外語來源、寫真人姓名。非中日韓語言的區塊維持較嚴的 `CORE_VARIANTS`：
 * 那裡出現「湾」「国」幾乎都是譯文掉回中文（ar 區塊曾整段是「台湾前 50 大企业」），
 * 放寬白名單會把最該抓的主權案例放掉。
 *
 * 加字進來前先問：**這個字在台灣是正常寫法，或出現在合法引用／人名裡嗎？**
 * 是 → 加，並在上面的校準紀錄寫下語料證據。否 → 那是外洩，該修內容不該改白名單。
 */

